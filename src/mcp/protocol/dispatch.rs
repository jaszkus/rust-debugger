fn gate(name: &str, state: &Arc<Mutex<AppState>>) -> Result<(), String> {
    let denied = "denied by workbench settings";
    if WRITE_TOOLS.contains(&name) || EXEC_TOOLS.contains(&name) {
        let s = state.lock().map_err(|_| "lock poisoned".to_string())?;
        if WRITE_TOOLS.contains(&name) && !s.allow_changes {
            return Err(format!(
                "{denied}: Allow changes is off. Enable Settings → AI and MCP → Allow changes."
            ));
        }
        if EXEC_TOOLS.contains(&name) && !s.allow_execution {
            return Err(format!(
                "{denied}: Allow execution is off. Enable Settings → AI and MCP → Allow execution."
            ));
        }
    }
    Ok(())
}

